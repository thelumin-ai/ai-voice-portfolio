import { NextResponse } from 'next/server'
import { requireAdmin } from '@/lib/auth/admin'
import { getServerApiKeys } from '@/lib/server/secrets'

export async function POST(req: Request) {
  try {
    const auth = await requireAdmin()
    if (auth.error) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
    }

    const body = await req.json().catch(() => null)
    const prompt = typeof body?.prompt === 'string' ? body.prompt.trim() : ''

    if (!prompt) {
      return NextResponse.json({ error: 'Prompt is required' }, { status: 400 })
    }

    if (prompt.length > 2000) {
      return NextResponse.json({ error: 'Prompt must be 2,000 characters or fewer' }, { status: 400 })
    }

    const keys = await getServerApiKeys()
    const apiKey = keys.gemini_api_key
    if (!apiKey) {
      return NextResponse.json({ error: 'Gemini API key not configured in settings' }, { status: 400 })
    }

    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-image:generateContent?key=${encodeURIComponent(apiKey)}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: { responseModalities: ['IMAGE'] },
        }),
        signal: AbortSignal.timeout(45_000),
      }
    )

    const data = await response.json().catch(() => ({}))

    if (!response.ok) {
      console.error('Gemini API Error:', data)
      return NextResponse.json(
        { error: data.error?.message || 'Failed to generate image' },
        { status: response.status }
      )
    }

    const parts = data?.candidates?.[0]?.content?.parts || []
    const imagePart = parts.find(
      (p: { inlineData?: { mimeType?: string; data?: string } }) =>
        typeof p?.inlineData?.mimeType === 'string' &&
        p.inlineData.mimeType.startsWith('image/') &&
        typeof p.inlineData.data === 'string'
    )

    if (!imagePart) {
      console.error('No image part found in Gemini image response')
      return NextResponse.json(
        { error: 'No image was generated by the model. Make sure your key supports image generation.' },
        { status: 500 }
      )
    }

    return NextResponse.json({
      base64: imagePart.inlineData.data,
      mimeType: imagePart.inlineData.mimeType || 'image/jpeg',
    })
  } catch (error) {
    console.error('Image Generation Error:', error)
    return NextResponse.json(
      { error: error instanceof Error ? error.message : 'Internal server error' },
      { status: 500 }
    )
  }
}
